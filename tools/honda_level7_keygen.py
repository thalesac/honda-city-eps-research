def _compute_key_word(word1, word2, val1, val2, val3, byte1, byte2):
    """
    Core computation function (reverse-engineered from 0x10003640 in DLL).

    This is a multi-path dispatcher based on ECU identifier ranges.
    Implements the exact computation from the DLL's machine code.
    """
    # The function dispatches based on ranges of word2 (ECU identifier)
    # Each path uses different combinations of ROL, ROR, XOR, ADD operations

    cx = word2 & 0xFFFF
    eax_val = word1 & 0xFFFF
    esi = val1 & 0xFFFF
    edi = val2 & 0xFFFF

    # Helper: signed 16-bit arithmetic
    def s16(v):
        v &= 0xFFFF
        return v

    def rol16(v, n):
        v &= 0xFFFF
        return ((v << n) | (v >> (16 - n))) & 0xFFFF

    def ror16(v, n):
        v &= 0xFFFF
        return ((v >> n) | (v << (16 - n))) & 0xFFFF

    # Path 1: (word2 + 0x5400) & 0xFFFF <= 3
    # i.e., word2 in {0xABFF, 0xAC00, 0xAC01, 0xAC02, 0xAC03} (but 0xABFF wraps)
    bx = s16(cx + 0x5400)
    if bx <= 3:
        result = s16(s16(eax_val ^ edi) + val3)
        return result

    # Path 2: word2 in [0xB1E0, 0xB1E3]
    if 0xB1E0 <= cx <= 0xB1E3:
        # Complex path with ROL/ROR
        ecx_local = s16(eax_val + esi)
        esi_local = s16(ecx_local)
        # ROL esi by byte1 bits
        for _ in range(byte1):
            esi_local = rol16(esi_local, 1)

        edx_local = s16(eax_val + edi)
        # ROR edx by byte2 bits
        for _ in range(byte2):
            edx_local = ror16(edx_local, 1)

        result = s16(s16(eax_val + val3) ^ edx_local ^ esi_local)
        return result

    # Path 3: (word2 + 0x54DF) & 0xFFFF <= 3
    # i.e., word2 in {0xAB20, 0xAB21, 0xAB22, 0xAB23, 0xAB24}
    bx2 = s16(cx + 0x54DF)
    if bx2 <= 3:
        # Same as B1E0 path
        ecx_local = s16(eax_val + esi)
        esi_local = s16(ecx_local)
        for _ in range(byte1):
            esi_local = rol16(esi_local, 1)

        edx_local = s16(eax_val + edi)
        for _ in range(byte2):
            edx_local = ror16(edx_local, 1)

        result = s16(s16(eax_val + val3) ^ edx_local ^ esi_local)
        return result

    # Path 4: (word2 + 0x57F0) & 0xFFFF <= 7
    # i.e., word2 in {0xA80F..0xA817} approx
    bx3 = s16(cx + 0x57F0)
    if bx3 <= 7:
        # XOR path with ROL
        result = s16(eax_val ^ esi)
        # ROL by byte1 bits
        for _ in range(byte1):
            result = rol16(result, 1)
        result = s16(result + val3)
        return result

    # Path 5: word2 in [0xB1EC, 0xB1EF]
    if 0xB1EC <= cx <= 0xB1EF:
        # Complex ROL/ROR/XOR
        ecx_local = s16(eax_val + esi)
        esi_local = s16(ecx_local)
        for _ in range(byte1):
            esi_local = rol16(esi_local, 1)

        eax_local = s16(eax_val + edi)
        for _ in range(byte2):
            eax_local = ror16(eax_local, 1)

        result = s16(eax_local ^ esi_local)
        result = s16(result + val3)
        return result

    # Path 6: word2 in [0x9A00, 0x9A03]
    if 0x9A00 <= cx <= 0x9A03:
        ecx_local = s16(eax_val + esi)
        esi_local = s16(ecx_local)
        for _ in range(byte1):
            esi_local = rol16(esi_local, 1)

        eax_local = s16(eax_val + edi)
        for _ in range(byte2):
            eax_local = ror16(eax_local, 1)

        result = s16(eax_local ^ esi_local)
        result = s16(result + val3)
        return result

    # Path 7: word2 in [0x8A00, 0x8A03]
    if 0x8A00 <= cx <= 0x8A03:
        ecx_local = s16(eax_val + esi)
        esi_local = s16(ecx_local)
        for _ in range(byte1):
            esi_local = rol16(esi_local, 1)

        eax_local = s16(eax_val + edi)
        for _ in range(byte2):
            eax_local = ror16(eax_local, 1)

        result = s16(eax_local ^ esi_local)
        result = s16(result + val3)
        return result

    # Path 8: (word2 + 0x5ABC) & 0xFFFF <= 3
    # i.e., word2 in {0xA543, 0xA544, 0xA545, 0xA546, 0xA547}
    bx4 = s16(cx + 0x5ABC)
    if bx4 <= 3:
        ecx_local = s16(eax_val + esi)
        esi_local = s16(ecx_local)
        for _ in range(byte1):
            esi_local = rol16(esi_local, 1)

        eax_local = s16(eax_val + edi)
        for _ in range(byte2):
            eax_local = ror16(eax_local, 1)

        result = s16(eax_local ^ esi_local)
        result = s16(result + val3)
        return result

    # Default path: same ROL/ROR/XOR pattern
    ecx_local = s16(eax_val + esi)
    esi_local = s16(ecx_local)
    for _ in range(byte1):
        esi_local = rol16(esi_local, 1)

    eax_local = s16(eax_val + edi)
    for _ in range(byte2):
        eax_local = ror16(eax_local, 1)

    result = s16(eax_local ^ esi_local)
    result = s16(result + val3)
    return result


def compute_key(seed_bytes):
    """
    Compute the Level 7 key for a 4-byte seed.

    Args:
        seed_bytes: 4-byte seed as bytes or list of ints

    Returns:
        4-byte key as bytes, or None if seed's word2 is not in the table
    """
    if len(seed_bytes) != 4:
        raise ValueError(f"Seed must be 4 bytes, got {len(seed_bytes)}")

    word1 = (seed_bytes[0] << 8) | seed_bytes[1]
    word2 = (seed_bytes[2] << 8) | seed_bytes[3]

    if word2 not in TABLE:
        return None

    val1, val2, val3, byte1, byte2 = TABLE[word2]

    key_word = _compute_key_word(word1, word2, val1, val2, val3, byte1, byte2)

    # Key = [computed_hi, computed_lo, seed[2], seed[3]]
    key = bytes([
        (key_word >> 8) & 0xFF,
        key_word & 0xFF,
        seed_bytes[2],
        seed_bytes[3]
    ])

    return key


